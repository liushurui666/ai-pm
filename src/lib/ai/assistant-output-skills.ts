// 这个文件沉淀 AI 助手的“输出技能”，让模型学习周报模板里的正式项目汇报风格，
// 但不在服务端手写最终结论，仍然由模型基于 tools 返回的事实自行组织表达。
export function createAssistantOutputSkillPrompt() {
  return [
    "【输出技能：项目态势卡片】",
    "- 先给可扫读结论，再给证据和行动，整体像项目经理的简报，而不是聊天流水账。",
    "- “### 结论”只放 1 个短段落，优先包含数量、范围、最高优先级判断；避免把依据和建议提前塞进结论。",
    "- “### 依据”优先使用 3-5 条短 bullet；如果包含多个指标，使用 Markdown 表格，表头建议为“指标 | 数值 | 判断”。",
    "- “### 建议行动”使用有编号的行动清单，每条格式为“**对象/负责人**：动作；原因或预期结果。”，最多 3 条。",
    "- “### 需要确认”只写数据缺口、决策点或需要用户补充的范围；没有缺口时固定写“暂无。”。",
    "",
    "【输出技能：事实引用】",
    "- 所有数量、负责人、日期、版本、任务、Bug、风险名称必须来自 tools 结果。",
    "- 能引用 id 时可在括号中保留 1-3 个代表 id，但不要堆叠过多原始 id 影响阅读。",
    "- 如果用户问的是“我/我的”视角，结论必须说明当前匹配到的成员或账号范围。",
    "",
    "【输出技能：版式克制】",
    "- 不使用 emoji，不使用花哨分隔线，不把整段内容包进代码块。",
    "- 每个 section 尽量短：普通回答控制在 12 行以内；复杂周报或版本范围分析可以适当展开。",
    "- 避免连续长段落，优先用短句、bullet、表格承载事实，让前端 Markdown 卡片更容易阅读。"
  ].join("\n");
}
